import { expect, test, type Page } from "@playwright/test";

const email = process.env.E2E_AUTH0_EMAIL;
const password = process.env.E2E_AUTH0_PASSWORD;
const credentialsAvailable = Boolean(email && password);

async function signIn(page: Page) {
  await page.goto("/auth/login?returnTo=%2Fassessment");

  const emailInput = page.locator('input[type="email"], input[name="username"], input[name="email"]').first();
  await expect(emailInput).toBeVisible();
  await emailInput.fill(email!);

  const passwordInput = page.locator('input[type="password"]').first();
  if (!(await passwordInput.isVisible().catch(() => false))) {
    await page.getByRole("button", { name: /continue|next/i }).click();
  }
  await expect(passwordInput).toBeVisible();
  await passwordInput.fill(password!);
  await page.getByRole("button", { name: /log in|continue|sign in/i }).click();
  await expect(page).toHaveURL(/\/assessment(?:[/?#]|$)/, { timeout: 60_000 });
}

async function choose(page: Page, question: string, answer: string) {
  await page.getByRole("group", { name: question }).getByRole("radio", { name: answer, exact: true }).check();
}

async function next(page: Page) {
  await page.getByRole("button", { name: "Next" }).click();
}

test.describe("Auth0 signup and questionnaire to Gemini", () => {
  test("the create-account route starts Auth0 Universal Login in signup mode", async ({ page, baseURL }) => {
    const signupEntry = await page.request.get("/sign-up", { maxRedirects: 0 });
    expect([301, 302, 303, 307, 308]).toContain(signupEntry.status());
    const loginPath = signupEntry.headers().location;
    expect(loginPath).toBeTruthy();
    expect(loginPath).toContain("/auth/login");
    expect(loginPath).toContain("screen_hint=signup");

    const authorization = await page.request.get(new URL(loginPath!, baseURL).toString(), { maxRedirects: 0 });
    expect([301, 302, 303, 307, 308]).toContain(authorization.status());
    const location = authorization.headers().location;
    expect(location).toBeTruthy();
    const authorizationUrl = new URL(location!);
    expect(authorizationUrl.searchParams.get("screen_hint")).toBe("signup");
    expect(authorizationUrl.searchParams.get("redirect_uri")).toBe(new URL("/auth/callback", baseURL).toString());
  });

  test("an authenticated user completes every applicable step and gets a live Gemini follow-up", async ({ page }) => {
    test.skip(!credentialsAvailable, "Set E2E_AUTH0_EMAIL and E2E_AUTH0_PASSWORD for Auth0 integration tests.");

    await signIn(page);
    await expect(page.getByRole("heading", { name: "Tax year & location" })).toBeVisible();

    await choose(page, "Which tax year do you need help with?", "2025 tax return");
    await choose(page, "Which state or jurisdiction did you live in during that year?", "Pennsylvania");
    await choose(page, "Did you move or live in multiple states during the year?", "No");
    await choose(page, "Where did you physically work during the year?", "Same state where I lived");
    await next(page);

    await expect(page.getByRole("heading", { name: "Personal situation" })).toBeVisible();
    await choose(page, "What is your age range?", "18–24");
    await choose(page, "Which best describes your education?", "Full-time student");
    await choose(page, "Will someone claim you as a dependent on their return for this tax year?", "No");
    await choose(page, "What filing status did you use or expect to use for the tax year?", "Single");
    await next(page);

    await expect(page.getByRole("heading", { name: "Income" })).toBeVisible();
    await page.getByRole("checkbox", { name: "W-2 employment" }).check();
    await choose(page, "Approximately how much income did you receive?", "$15,000–$40,000");
    await choose(page, "Do you have your income tax documents?", "Yes, all relevant documents");
    await next(page);

    await expect(page.getByRole("heading", { name: "Education" })).toBeVisible();
    await choose(page, "Did you pay college tuition or other education expenses?", "Yes");
    await choose(page, "Did you receive scholarships or grants?", "Yes");
    await choose(page, "Did you pay student loan interest during the year?", "Yes");
    await next(page);

    await expect(page.getByRole("heading", { name: "State & local taxes" })).toBeVisible();
    await choose(page, "Did you live or work in a location that may have local income taxes?", "Yes");
    await choose(page, "Were local taxes withheld from your paycheck?", "No");
    const geminiResponsePromise = page.waitForResponse((response) =>
      response.url().includes("/api/gemini/adaptive-follow-up"),
    );
    await next(page);

    await expect(page.getByRole("heading", { name: "Review" })).toBeVisible();
    await expect(page.getByRole("heading", { name: "A few more details" })).toBeVisible();
    await expect(page.getByText("Generated by Gemini", { exact: true })).toBeVisible({ timeout: 90_000 });
    await expect(page.getByText("Question 1 of 3:")).toBeVisible();
    const geminiResponse = await geminiResponsePromise;
    expect(geminiResponse.status()).toBe(200);
    const payload = await geminiResponse.json();
    expect(payload.followUp.source).toBe("gemini");

    // Answer each requested fact and verify that the flow eventually requests advice.
    for (let turn = 1; turn <= 3; turn++) {
      const question = page.getByText(`Question ${turn} of 3:`);
      if (!(await question.isVisible().catch(() => false))) break;
      const form = question.locator("..");
      const select = form.locator("select");
      if (await select.count()) await select.selectOption({ index: 1 });
      else await form.locator('input[type="number"]').fill("0");

      const continuation = page.waitForResponse((response) =>
        /\/api\/gemini\/(adaptive-follow-up|explain)$/.test(new URL(response.url()).pathname),
      );
      await form.getByRole("button", { name: "Submit answer" }).click();
      const response = await continuation;
      expect([200, 503]).toContain(response.status());
      if (response.url().includes("/api/gemini/explain")) {
        expect(response.status()).toBe(200);
        const advice = await response.json();
        expect(advice.advice.summary).toBeTruthy();
        break;
      }
    }
    await expect(page.getByRole("heading", { name: "Personalized guidance" })).toBeVisible({ timeout: 90_000 });
  });
});
